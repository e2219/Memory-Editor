export function revealStory(state: SessionState): string {
  if (!state.ending) throw new Error("revelation_requires_ending");
  return "【故事底稿 · 完整剧透】\n\n" + STORY_BACKGROUND
    .map((chapter) => `${chapter.title}\n\n${chapter.text}`).join("\n\n") +
    `\n\n【本局记录】\n你完成了 ${state.turn} 个治疗回合。` +
    (state.progress.submittedConclusion
      ? `\n你提交的结论：${state.progress.submittedConclusion}`
      : "\n本局没有提交正式结论。") +
    "\n揭底只供玩家阅读，不会发送给伊莱或联系人，也不会改变本局结局。";
}
